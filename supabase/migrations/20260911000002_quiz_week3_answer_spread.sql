-- =========================================================
-- 3주차 퀴즈 — 정답 위치를 흩는다
-- =========================================================
--
-- 앞 마이그레이션에서 여섯 문항의 정답이 전부 1번에 몰렸다. 화면(QuizPlayer)은
-- 보기를 섞지 않고 저장된 순서 그대로 그리므로, 학생이 내용을 몰라도 1번을 찍으면
-- 다 맞는다. 보기 순서를 바꿔 정답을 0~3번에 흩어 놓는다.
--
-- **답이 들어온 뒤에는 이렇게 고치면 안 된다.** quiz_answers.selected_index 는
-- 위치를 가리키므로, 순서를 바꾸면 이미 채점된 답이 엉뚱한 보기를 가리키게 된다.
-- 이 마이그레이션은 3주차에 답이 0건일 때 적용했다.

update public.quiz_questions set
  choices = '["영국에 철광석이 세계에서 가장 많이 묻혀 있었다", "프랑스보다 인구가 훨씬 많았다", "석탄이 얕게 묻혀 있었고, 탄광에 찬 물을 퍼낼 기계가 절실했다", "왕실이 발명가에게 직접 월급을 주었다"]',
  answer_index = 2
where week_id = 3 and order_no = 1;

update public.quiz_questions set
  choices = '["기계가 사람보다 항상 정확하다", "핀은 수작업으로 만들어야 품질이 좋다", "공장은 도시보다 농촌에 있어야 한다", "공정을 나눠 맡으면 생산량이 극적으로 늘어난다"]',
  answer_index = 3
where week_id = 3 and order_no = 2;

-- 3번은 그대로 0번에 둔다. 전부 0번을 피하려다 0번이 하나도 없으면 그것도 규칙이 된다.

update public.quiz_questions set
  choices = '["도자기를 유럽에서 처음으로 구워냈다", "장인 한 사람이 처음부터 끝까지 만들게 했다", "''형태를 정하는 일''과 ''반복 생산하는 일''을 분리해 관리했다", "왕실에만 납품하고 일반 판매를 막았다"]',
  answer_index = 2
where week_id = 3 and order_no = 4;

update public.quiz_questions set
