-- =========================================================
-- 팀 논의 글에 작성자 닉네임을 함께 저장한다
-- =========================================================
--
-- `profiles` 는 "본인 행만 읽기"(교수자만 전체)라서, 학생이 공유판을 보면
-- 남의 글에 붙은 닉네임이 전부 null 로 와서 "익명"으로 보였다.
-- 그렇다고 profiles 읽기를 열 수는 없다 — RLS 는 행 단위라 select 를 허용하면
-- 닉네임뿐 아니라 이름·학번까지 모든 학생에게 열린다.
-- 그래서 글을 올릴 때 닉네임을 함께 적어 둔다(작성 시점 스냅샷).

alter table public.discussion_posts
  add column author_nickname text;
